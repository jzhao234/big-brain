import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { frontmatterEnd } from "./frontmatter.js";

/**
 * The line `agents render` puts right after a generated SKILL.md's
 * frontmatter. It names the source to edit and carries a hash of everything
 * render wrote, so a later render can tell a copy it may overwrite (unedited)
 * from one someone changed by hand, with no state outside the file: it works
 * the same in every clone of the vault.
 */
const MARKER_RE = /^<!-- Generated by big-brain from (.+?): .* render:([0-9a-f]{12}) -->\r?$/;

export function markerLine(source: string, hash: string): string {
  return `<!-- Generated by big-brain from ${source}: edit that file, then run \`big-brain agents render\`. render:${hash} -->`;
}

/** Hash of a skill folder's files (relative paths and bytes). */
export function hashFiles(files: Map<string, Buffer>): string {
  const hash = crypto.createHash("sha256");
  for (const rel of [...files.keys()].sort()) {
    const bytes = files.get(rel) as Buffer;
    // Byte length first, so no file's content can pass for the next entry.
    hash.update(`f\0${rel}\0${bytes.length}\0`).update(bytes);
  }
  return hash.digest("hex").slice(0, 12);
}

/** Every file in a folder by relative POSIX path; refuses symlinks. */
export function readTree(dir: string): Map<string, Buffer> {
  const files = new Map<string, Buffer>();
  const visit = (abs: string, rel: string): void => {
    for (const entry of fs
      .readdirSync(abs, { withFileTypes: true })
      .sort((a, b) => a.name.localeCompare(b.name))) {
      if (entry.name === ".DS_Store") continue;
      const childAbs = path.join(abs, entry.name);
      const childRel = rel ? `${rel}/${entry.name}` : entry.name;
      if (entry.isSymbolicLink()) throw new Error(`${childAbs} is a symlink`);
      if (entry.isDirectory()) visit(childAbs, childRel);
      else if (entry.isFile()) files.set(childRel, fs.readFileSync(childAbs));
    }
  };
  visit(dir, "");
  return files;
}

export interface Marker {
  /** The source the marker names, relative to the vault. */
  source: string;
  /** Hash of the generated files, marker line excluded. */
  hash: string;
}

/**
 * Split a generated SKILL.md into its marker and the text without the marker
 * line. Undefined when the file has no marker in its place.
 */
export function splitMarker(skill: string): { marker: Marker; rest: string } | undefined {
  const end = frontmatterEnd(skill);
  if (end === undefined) return undefined;
  const newline = skill.indexOf("\n", end);
  const lineEnd = newline === -1 ? skill.length : newline;
  const m = MARKER_RE.exec(skill.slice(end, lineEnd));
  if (!m) return undefined;
  return {
    marker: { source: m[1] as string, hash: m[2] as string },
    rest: skill.slice(0, end) + skill.slice(newline === -1 ? lineEnd : newline + 1),
  };
}

/** The marker of a generated skill folder, or undefined when it has none. */
export function readMarker(dir: string): Marker | undefined {
  let text: string;
  try {
    text = fs.readFileSync(path.join(dir, "SKILL.md"), "utf8");
  } catch {
    return undefined;
  }
  return splitMarker(text)?.marker;
}

/** Whether a folder holds a skill `agents render` generated. */
export function isGeneratedSkill(dir: string): boolean {
  return readMarker(dir) !== undefined;
}

/**
 * Whether a generated folder is still exactly what render wrote: its files,
 * minus the marker line, hash to the marker's value.
 */
export function generatedUnedited(files: Map<string, Buffer>): boolean {
  const skill = files.get("SKILL.md");
  if (!skill) return false;
  const split = splitMarker(skill.toString("utf8"));
  if (!split) return false;
  const rest = new Map(files);
  rest.set("SKILL.md", Buffer.from(split.rest, "utf8"));
  return hashFiles(rest) === split.marker.hash;
}
